// Build-time tool: writes a C++ source that embeds a set of files as byte arrays, keyed by
// their path relative to a root directory (see plugin/src/FactoryContent.h).
//
//   EmbedFiles <out.cpp> <root> <list-file>
//
// list-file holds one absolute file path per line. Output is deterministic (sorted by
// relative path), so an unchanged input set gives an unchanged source file.
#include <algorithm>
#include <cstdio>
#include <filesystem>
#include <fstream>
#include <iterator>
#include <string>
#include <vector>

namespace fs = std::filesystem;

int main (int argc, char** argv)
{
    if (argc != 4)
    {
        std::fprintf (stderr, "usage: EmbedFiles <out.cpp> <root> <list-file>\n");
        return 2;
    }

    const fs::path out = argv[1];
    const fs::path root = fs::absolute (argv[2]).lexically_normal();
    std::vector<std::pair<std::string, fs::path>> files;

    {
        std::ifstream list (argv[3]);
        std::string line;
        while (std::getline (list, line))
        {
            if (line.empty()) continue;
            const fs::path p = fs::absolute (line).lexically_normal();
            std::string rel = p.lexically_relative (root).generic_string();
            if (rel.empty() || rel.rfind ("..", 0) == 0) rel = p.filename().generic_string();
            files.emplace_back (std::move (rel), p);
        }
    }
    std::sort (files.begin(), files.end());

    std::string src;
    src += "// Generated by EmbedFiles. Do not edit.\n#include \"FactoryContent.h\"\n#include <algorithm>\n#include <string_view>\n\n"
           "namespace acid::plugin\n{\nnamespace\n{\n";

    std::size_t index = 0;
    for (const auto& [rel, path] : files)
    {
        std::ifstream in (path, std::ios::binary);
        if (! in)
        {
            std::fprintf (stderr, "EmbedFiles: cannot read %s\n", path.c_str());
            return 1;
        }
        const std::vector<unsigned char> bytes ((std::istreambuf_iterator<char> (in)), std::istreambuf_iterator<char>());
        src += "const unsigned char kData" + std::to_string (index) + "[] = {";
        char buf[8];
        for (std::size_t i = 0; i < bytes.size(); ++i)
        {
            if (i % 32 == 0) src += "\n   ";
            std::snprintf (buf, sizeof (buf), " %u,", static_cast<unsigned> (bytes[i]));
            src += buf;
        }
        if (bytes.empty()) src += " 0";   // an empty file still needs one element
        src += "\n};\n";
        ++index;
    }

    src += "\nconst FactoryFile kFiles[] = {\n";
    index = 0;
    for (const auto& [rel, path] : files)
    {
        std::string escaped;
        for (const char c : rel)
        {
            if (c == '\\' || c == '"') escaped += '\\';
            escaped += c;
        }
        const auto size = fs::file_size (path);
        src += "    { \"" + escaped + "\", kData" + std::to_string (index) + ", " + std::to_string (size) + "u },\n";
        ++index;
    }
    if (files.empty())
        src += "    { \"\", nullptr, 0u },\n";
    src += "};\n}\n\n";
    src += "std::span<const FactoryFile> factoryFiles() noexcept\n{\n    return { kFiles, " + std::to_string (files.size()) + "u };\n}\n\n";
    src += "const FactoryFile* findFactoryFile (std::string_view path) noexcept\n{\n"
           "    const auto all = factoryFiles();\n"
           "    const auto it = std::lower_bound (all.begin(), all.end(), path,\n"
           "                                      [] (const FactoryFile& f, std::string_view p) { return std::string_view (f.path) < p; });\n"
           "    return it != all.end() && std::string_view (it->path) == path ? &*it : nullptr;\n}\n}\n";

    std::ofstream o (out, std::ios::binary);
    if (! o || ! o.write (src.data(), static_cast<std::streamsize> (src.size())))
    {
        std::fprintf (stderr, "EmbedFiles: cannot write %s\n", out.c_str());
        return 1;
    }
    return 0;
}
